import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { JSDOM } from "jsdom";
import { OCCASIONS, applyOccasionFilters, getOccasionAppUrl, getOccasionBySlug } from "./occasions";
import {
  STYLE_BRIEF_LINES,
  TONE_BRIEF_LINES,
  TOPIC_BRIEF_LINES,
} from "../../convex/data/briefLines";
import { renderPageResponse } from "../../api/_pageMetadata";

const indexHtml = `<!doctype html>
<html lang="en">
  <head>
    <title>Homepage title</title>
  </head>
  <body><div id="root"></div></body>
</html>`;

describe("occasions config", () => {
  it("maps every occasion filter slug to a real style, tone, or topic", () => {
    const slugs = new Set<string>();

    for (const occasion of OCCASIONS) {
      expect(slugs.has(occasion.slug)).toBe(false);
      slugs.add(occasion.slug);
      expect(occasion.sampleCards.length).toBeGreaterThanOrEqual(3);
      expect(getOccasionBySlug(occasion.slug)).toBe(occasion);
      expect(getOccasionAppUrl(occasion)).toBe(`/app?occasion=${occasion.slug}`);

      if (occasion.filters.style) {
        expect(STYLE_BRIEF_LINES).toHaveProperty(occasion.filters.style);
      }
      if (occasion.filters.tone) {
        expect(TONE_BRIEF_LINES).toHaveProperty(occasion.filters.tone);
      }
      if (occasion.filters.topic) {
        expect(TOPIC_BRIEF_LINES).toHaveProperty(occasion.filters.topic);
      }
      expect(
        Boolean(occasion.filters.style || occasion.filters.tone || occasion.filters.topic),
      ).toBe(true);
    }
  });

  it("labels every sample card with a real style, tone and topic", () => {
    for (const occasion of OCCASIONS) {
      for (const card of occasion.sampleCards) {
        expect(STYLE_BRIEF_LINES).toHaveProperty(card.style);
        expect(TONE_BRIEF_LINES).toHaveProperty(card.tone);
        expect(TOPIC_BRIEF_LINES).toHaveProperty(card.topic);
      }
    }
  });

  it("gives every occasion one filter that all its sample cards fit", () => {
    for (const occasion of OCCASIONS) {
      const filters = Object.entries(occasion.filters).filter(([, value]) => value);
      expect(filters, occasion.slug).toHaveLength(1);
      const [[key, value]] = filters as [["style" | "tone" | "topic", string]];
      for (const card of occasion.sampleCards) {
        expect(card[key], `${occasion.slug}: ${card.text}`).toBe(value);
      }
    }
  });

  it("lists exactly the configured occasion pages in the sitemap", () => {
    const sitemap = readFileSync(path.resolve(process.cwd(), "public/sitemap.xml"), "utf8");
    const listed = [...sitemap.matchAll(/\/occasions\/([^<]+)<\/loc>/g)].map((match) => match[1]);
    expect(listed.sort()).toEqual(OCCASIONS.map((occasion) => occasion.slug).sort());
    expect(sitemap).toContain("<loc>https://breaktheiceberg.com/occasions</loc>");
  });

  it.each(["constructor", "toString", "hasOwnProperty", "__proto__"])(
    "returns undefined for the built-in object key %s",
    (slug) => {
      expect(getOccasionBySlug(slug)).toBeUndefined();
    },
  );

  it("renders unique SEO metadata for /occasions and each occasion page, and 404 for unknown slugs", () => {
    const indexResponse = renderPageResponse(indexHtml, "/occasions");
    expect(indexResponse.statusCode).toBe(200);
    const indexDoc = new JSDOM(indexResponse.html).window.document;
    expect(indexDoc.title).toContain("Occasion");
    expect(indexDoc.querySelector('meta[name="robots"]')?.getAttribute("content")).toBe(
      "index, follow",
    );

    const detailResponse = renderPageResponse(indexHtml, "/occasions/dinner-party");
    expect(detailResponse.statusCode).toBe(200);
    const detailDoc = new JSDOM(detailResponse.html).window.document;
    expect(detailDoc.title).toBe("Dinner Party Conversation Starters | Break the Ice(berg)");
    expect(detailDoc.querySelector('link[rel="canonical"]')?.getAttribute("href")).toBe(
      "https://breaktheiceberg.com/occasions/dinner-party",
    );

    const missingResponse = renderPageResponse(indexHtml, "/occasions/not-real");
    expect(missingResponse.statusCode).toBe(404);
    const missingDoc = new JSDOM(missingResponse.html).window.document;
    expect(missingDoc.querySelector('meta[name="robots"]')?.getAttribute("content")).toBe(
      "noindex, nofollow",
    );
  });

  // Generated by /ship test coverage audit.
  // Value: protects=applyOccasionFilters keeps explicit filters, fills only missing or empty ones, drops occasion; fails_when=it overwrites an explicit filter or leaves occasion; why_new=only reached indirectly via page mocks; seam=none; no_claim=none beyond protects
  it.each([
    ["occasion=x&tone=witty", { tone: "cozy", topic: "food" }, "tone=witty&topic=food"],
    ["occasion=x&tone=", { tone: "cozy" }, "tone=cozy"],
    ["occasion=x&page=2", {}, "page=2"],
  ])("applyOccasionFilters(%s)", (query, filters, expected) => {
    const params = new URLSearchParams(query);
    applyOccasionFilters(params, { filters });
    expect(params.toString()).toBe(expected);
  });
});
