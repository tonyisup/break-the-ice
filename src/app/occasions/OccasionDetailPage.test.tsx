import { describe, expect, it, vi, beforeEach } from "vitest";
import { act, fireEvent, render, screen } from "@testing-library/react";
import { toast } from "sonner";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import OccasionDetailPage from "./OccasionDetailPage";
import { getOccasionBySlug } from "@/config/occasions";

vi.mock("sonner", () => ({ toast: { success: vi.fn(), error: vi.fn() } }));
vi.mock("@/hooks/useTheme", () => ({ useTheme: () => ({ theme: "light", setTheme: vi.fn() }) }));
vi.mock("@/components/PublicChrome", () => ({
  PublicHeader: () => null,
  PublicFooter: () => null,
}));

const renderAt = (path: string) =>
  render(
    <MemoryRouter initialEntries={[path]}>
      <Routes>
        <Route path="/occasions/:slug" element={<OccasionDetailPage />} />
      </Routes>
    </MemoryRouter>,
  );

describe("OccasionDetailPage", () => {
  beforeEach(() => {
    window.scrollTo = vi.fn() as unknown as typeof window.scrollTo;
  });

  it.each(["constructor", "toString", "not-real"])("shows the not-found page for /occasions/%s", (slug) => {
    renderAt(`/occasions/${slug}`);
    expect(screen.getByText("Error 404")).toBeInTheDocument();
    expect(screen.queryByRole("button", { name: /draw another/i })).toBeNull();
  });

  it("names each sample card's copy button after its question", () => {
    renderAt("/occasions/road-trip");
    for (const card of getOccasionBySlug("road-trip")!.sampleCards) {
      expect(screen.getByRole("button", { name: `Copy: ${card.text}` })).toBeInTheDocument();
    }
  });

  it("starts the next occasion at its first card and the top of the page", () => {
    const firstDate = getOccasionBySlug("first-date")!;
    const dinnerParty = getOccasionBySlug("dinner-party")!;
    renderAt("/occasions/dinner-party");

    fireEvent.click(screen.getByRole("button", { name: /draw another/i }));
    expect(screen.getAllByText(dinnerParty.sampleCards[1].text).length).toBeGreaterThan(1);
    vi.mocked(window.scrollTo).mockClear();

    fireEvent.click(screen.getByRole("link", { name: firstDate.name }));

    expect(screen.getAllByText(firstDate.sampleCards[0].text).length).toBeGreaterThan(1);
    expect(window.scrollTo).toHaveBeenCalledWith(0, 0);
  });

  // Generated by /ship test coverage audit.
  // Value: protects=Draw another cycles back to the first sample card after the last; fails_when=the modulo wrap is dropped and the card blanks out; why_new=existing test only draws once; seam=none; no_claim=none beyond protects
  it("wraps Draw another back to the first sample card", () => {
    const dinnerParty = getOccasionBySlug("dinner-party")!;
    renderAt("/occasions/dinner-party");
    const draw = screen.getByRole("button", { name: /draw another/i });
    for (let i = 0; i < dinnerParty.sampleCards.length; i++) fireEvent.click(draw);
    expect(screen.getAllByText(dinnerParty.sampleCards[0].text).length).toBeGreaterThan(1);
  });

  // Generated by /ship test coverage audit.
  // Value: protects=copying a sample card shows Copied on success and an error toast when the clipboard rejects; fails_when=the catch or copied state is removed; why_new=no copy test existed; seam=none; no_claim=real clipboard permission (mocked navigator.clipboard and sonner)
  it("copies a sample card and reports a clipboard failure", async () => {
    const dinnerParty = getOccasionBySlug("dinner-party")!;
    const writeText = vi.fn().mockResolvedValueOnce(undefined).mockRejectedValueOnce(new Error("denied"));
    Object.defineProperty(navigator, "clipboard", { value: { writeText }, configurable: true });
    renderAt("/occasions/dinner-party");
    const copy = screen.getByRole("button", { name: "Copy sample question" });

    await act(async () => { fireEvent.click(copy); });
    expect(writeText).toHaveBeenCalledWith(dinnerParty.sampleCards[0].text);
    expect(toast.success).toHaveBeenCalled();
    expect(copy).toHaveTextContent("Copied");

    await act(async () => { fireEvent.click(copy); });
    expect(toast.error).toHaveBeenCalledWith("Couldn’t copy to clipboard");
  });
  it("keeps Copied on a card copied again until its own two seconds end", async () => {
    vi.useFakeTimers();
    try {
      const [first, second] = getOccasionBySlug("road-trip")!.sampleCards;
      Object.defineProperty(navigator, "clipboard", {
        value: { writeText: vi.fn().mockResolvedValue(undefined) },
        configurable: true,
      });
      renderAt("/occasions/road-trip");
      const copyFirst = screen.getByRole("button", { name: `Copy: ${first.text}` });
      const copySecond = screen.getByRole("button", { name: `Copy: ${second.text}` });

      await act(async () => { fireEvent.click(copyFirst); });
      await act(async () => { vi.advanceTimersByTime(500); fireEvent.click(copySecond); });
      await act(async () => { vi.advanceTimersByTime(500); fireEvent.click(copyFirst); });
      // The first copy's timer would fire now; the latest copy should still read Copied.
      await act(async () => { vi.advanceTimersByTime(1100); });
      expect(copyFirst).toHaveTextContent("Copied");

      await act(async () => { vi.advanceTimersByTime(1000); });
      expect(copyFirst).toHaveTextContent("Copy");
      expect(copyFirst).not.toHaveTextContent("Copied");
    } finally {
      vi.useRealTimers();
    }
  });
});
